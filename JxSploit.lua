			for i, target in ipairs(targets) do
				if not tried[i] then
					local d = slotAlive(i) and (slots[i].pos - target.pos).Magnitude or math.huge
					if d > REPLACE_DIST and (not pickDist or d > pickDist) then
						pick = i; pickDist = d
					end
				end
			end
			if not pick then break end
			tried[pick] = true
			replaceSlotClassic(token, tool, pick, targets[pick])
			task.wait(CLASSIC_GAP)
		end
	end
