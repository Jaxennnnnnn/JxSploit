	local function buildTargetsRandom(char, hrp, count)
		local ignore = { char }
		local hum    = char:FindFirstChildOfClass("Humanoid")
		local seat   = hum and hum.SeatPart
		if seat then table.insert(ignore, seat:FindFirstAncestorOfClass("Model") or seat) end
		local center       = hrp.Position
		local centerResult = rayDown(center, ignore)
		if not centerResult then return nil end
		lastGroundY = centerResult.Position.Y
		local targets = {}
		for i = 1, count do
			local angle  = math.random() * math.pi * 2
			local radius = math.random() * auraRadius
			local offset = Vector3.new(math.cos(angle) * radius, 0, math.sin(angle) * radius)
			local origin = center + offset
			local result  = rayDown(Vector3.new(origin.X, center.Y, origin.Z), ignore)
			local ground  = result or centerResult
			targets[i] = { part = ground.Instance, pos = Vector3.new(origin.X, ground.Position.Y - AURA_DEPTH, origin.Z) }
		end
		return targets
	end
	local function buildTargets(char, hrp)
