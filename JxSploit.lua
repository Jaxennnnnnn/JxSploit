		if watchConn then watchConn:Disconnect(); watchConn=nil end
		seenP={}; claimedP={}; pendingP={}
	end
	local MATCH_R = 16
	local function vnMatchPending()
		local i = 1
		while i <= #pendingP do
			local model = pendingP[i]
			local skip  = false
			if not model.Parent or claimedP[model] then
				table.remove(pendingP, i); skip=true
			end
			if not skip then
				local pos
				local touch=model:FindFirstChild("Touch")
				if touch and touch:IsA("BasePart") then
					pos=touch.Position
				elseif model:IsA("BasePart") then
					pos=model.Position
				elseif model:IsA("Model") then
					local ok2,p=pcall(function() return model:GetPivot().Position end)
					if ok2 then pos=p end
				end
				if pos then
					local best,bestD
					for _,entry in ipairs(placedProps) do
						if not entry.model then
							local d=(entry.pos-pos).Magnitude
							if d<MATCH_R and (not bestD or d<bestD) then best=entry; bestD=d end
						end
					end
					if best then
						best.model=model; claimedP[model]=true
						table.remove(pendingP,i); skip=true
					end
				end
				if not skip then i+=1 end
			end
		end
	end
	local function vnBuildSpots(center,ignore)
		local spots={}
		local centerRay=vnRayDown(center,ignore)
		local groundY=centerRay and centerRay.Position.Y or (center.Y-3)
		for _,ring in ipairs(TARGET_RINGS) do
			for i=1,ring.count do
				local angle=(i/ring.count)*math.pi*2
				local offset=Vector3.new(math.cos(angle)*ring.radius,0,math.sin(angle)*ring.radius)
				local origin=center+offset
				local ray=vnRayDown(origin,ignore)
				local ground=ray and ray.Instance or (centerRay and centerRay.Instance)
				local gy=ray and ray.Position.Y or groundY
				table.insert(spots,{
					part=ground,
					pos=Vector3.new(origin.X, gy-TARGET_DEPTH, origin.Z),
				})
			end
		end
		return spots
	end
