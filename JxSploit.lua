	-- NEW engine (fast): despawns the stale slots in one fast wave (~CYCLE_TIME
	-- total), then spawns the replacements in a second fast wave (~CYCLE_TIME
	-- total). No per-slot blocking confirmation wait - the background matcher
	-- above confirms independently, which is what makes this fast.
	local function auraCycleFast(token, moving, char, hrp, tool)
		if moving and auraMethod == "circular" then spin += SPIN_STEP end
		local targets = buildTargets(char, hrp)
		if not targets then return end

		local toReplace = {}
		for i, target in ipairs(targets) do
			local d = slotAlive(i) and (slots[i].pos - target.pos).Magnitude or math.huge
			if d > REPLACE_DIST then table.insert(toReplace, i) end
		end
		if #toReplace == 0 then return end

		if featureState.auradelete then
			local gap1 = math.max(0.01, CYCLE_TIME / #toReplace)
			for _, i in ipairs(toReplace) do
				if not auraEnabled or token ~= auraToken then return end
				if slots[i] then deleteSlot(tool, i) end
				task.wait(gap1)
			end
		end

